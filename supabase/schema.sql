-- Run once in the Supabase SQL editor. Dates represent store-local business days.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  sku text not null unique,
  name text not null,
  category text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0)
);
create table if not exists public.sales_transactions (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id),
  quantity_sold integer not null check (quantity_sold >= 0),
  sale_date date not null,
  store_location text not null
);
create index if not exists sales_product_date_idx on public.sales_transactions(product_id, sale_date);
create table if not exists public.external_factors (
  date date primary key,
  is_holiday boolean not null default false,
  local_price_index double precision not null default 1.0,
  weather_condition text not null default 'unknown'
);
create table if not exists public.demand_forecasts (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id),
  forecast_date date not null,
  predicted_demand double precision not null check (predicted_demand >= 0),
  lower_bound double precision not null check (lower_bound >= 0),
  upper_bound double precision not null,
  model_version text not null,
  created_at timestamptz not null default now(),
  check (lower_bound <= predicted_demand and predicted_demand <= upper_bound)
);
create index if not exists forecast_product_date_idx on public.demand_forecasts(product_id, forecast_date);
-- Service-role access bypasses RLS. No public client access is granted by these policies.
alter table public.products enable row level security;
alter table public.sales_transactions enable row level security;
alter table public.external_factors enable row level security;
alter table public.demand_forecasts enable row level security;
