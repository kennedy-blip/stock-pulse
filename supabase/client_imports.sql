-- Separate from the shared demonstration tables. The service role bypasses RLS;
-- the API must authenticate and scope every operation to the verified user ID.
create table if not exists public.client_sales_imports (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  import_hash text not null,
  row_number integer not null check (row_number >= 2),
  sku text not null check (length(sku) between 1 and 100),
  sale_date date not null,
  quantity_sold integer not null check (quantity_sold >= 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  store_location text not null default '',
  created_at timestamptz not null default now(),
  unique (owner_id, import_hash, row_number)
);
create index if not exists client_sales_owner_date_idx on public.client_sales_imports(owner_id, sale_date);
alter table public.client_sales_imports enable row level security;
-- No direct client policies: authenticated users access this table only via
-- server-side routes that verify the bearer token and bind owner_id themselves.
